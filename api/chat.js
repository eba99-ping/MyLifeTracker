import { GoogleGenAI } from "@google/genai";

export default async function handler(req, res) {

  if (req.method !== "POST") {
    return res.status(405).json({
      error: "POST request required"
    });
  }

  try {

    const {
      message,
      tracker
    } = req.body || {};

    if (!message || !message.trim()) {
      return res.status(400).json({
        error: "Асуулт хоосон байна."
      });
    }

    const apiKey =
      process.env.GEMINI_API_KEY;

    if (!apiKey) {
      return res.status(500).json({
        error:
          "GEMINI_API_KEY тохируулагдаагүй байна."
      });
    }

    const ai =
      new GoogleGenAI({
        apiKey
      });

    const trackerInfo =
      JSON.stringify(
        tracker || {},
        null,
        2
      );

    const prompt = `
Хэрэглэгчийн My Life Tracker мэдээлэл:

${trackerInfo}

Хэрэглэгчийн асуулт:

${message.trim()}

Энэ мэдээллийг ашиглан хэрэглэгчид бодитой, хэрэгжүүлэхэд амархан зөвлөгөө өг.
`;

    const response =
      await ai.models.generateContent({

        model: "gemini-3.6-flash",

        contents: prompt,

        config: {

          systemInstruction: `
Чи бол My Life Tracker аппын хувийн AI Coach.

ХЭЛ:
- Монгол хэлээр хариул.
- Монгол хэлний зөв дүрэмтэй, байгалийн, ойлгомжтой хэл ашигла.
- Хэт робот шиг битгий ярь.
- Найрсаг боловч бодитой бай.

ЧИНИЙ ҮҮРЭГ:
- Хэрэглэгчийн өдөр тутмын амьдралыг зохион байгуулахад туслах.
- Өнөөдрийн tracker мэдээллийг ашиглан зөвлөгөө өгөх.
- Хичээл болон суралцах төлөвлөгөө гаргах.
- Python, программчлал, AI сурахад туслах.
- Англи болон Орос хэл сурахад туслах.
- Цагийн менежмент хийхэд туслах.
- Мөнгөний зарцуулалтаа хянахад туслах.
- Өдрийн хийх зүйлсийг эрэмбэлэх.
- Зорилгоо жижиг алхмуудад хуваах.
- Өдрийн тэмдэглэл дээр үндэслэн эргэцүүлэл хийхэд туслах.
- Эрүүл, тогтвортой дадлыг дэмжих.

ХАРИУЛТЫН ДҮРЭМ:
1. Асуултад шууд хариул.
2. Боломжтой бол 3-7 богино хэсэг ашигла.
3. Хэрэггүй урт тайлбар бүү өг.
4. Хэрэгжүүлэх алхмуудыг 1, 2, 3 гэж тодорхой бич.
5. Хэрэглэгчийн tracker мэдээлэлд байхгүй зүйлийг зохиож бүү хэл.
6. Мэдэхгүй зүйлээ мэдэхгүй гэж хэл.
7. Тоо бодох шаардлагатай бол зөв тооц.
8. Хэрэглэгчийн хийсэн зүйлсийг магтаж болно, гэхдээ хэтрүүлж болохгүй.
9. Хийгээгүй зүйлсийг загнахгүй.
10. Нэг өдөр бүхнийг төгс хийх шаардлагагүй гэдгийг сануул.
11. Эрүүл мэндтэй холбоотой асуудалд аюулгүй, ерөнхий зөвлөгөө өг.
12. Vape болон бусад никотины хэрэглээг дэмжихгүй. Хэрэглэгч гарахыг хүсвэл аюулгүй, бодитой дэмжлэг өг.
13. Хоол, дасгалын талаар хэт хатуу хоолны дэглэм, эрсдэлтэй жин хасалт санал болгохгүй.
14. Хэрэглэгч сурагч тул хичээл, амралт, нойрыг тэнцвэртэй авч үз.
15. Хэрэглэгч "өнөөдөр юу хийх вэ?" гэж асуувал tracker-ийн мэдээллээс хамгийн чухал 3-5 ажлыг санал болго.
16. Хэрэглэгч "би юу дутуу хийсэн бэ?" гэж асуувал tracker-ийн мэдээллийг шалгаад тодорхой хэл.
17. Хэрэглэгч "надад төлөвлөгөө гарга" гэвэл бодитой, цаг хугацаатай төлөвлөгөө өг.

ӨНӨӨДРИЙН ЗОРИЛГО:
Хэрэглэгчийг нэг дор хэт олон зүйл хийхийг шаардахгүй.
Өнөөдөр хийх хамгийн чухал зүйлсийг эрэмбэлж өг.
Жижиг тогтвортой алхмыг урт хугацааны зорилгоос илүүд үз.

ХАРИУЛТЫН ХЭВ МАЯГ:
- Монгол хэл
- Богино
- Тодорхой
- Найрсаг
- Практик
          `,

          temperature: 0.35,

          maxOutputTokens: 500

        }

      });

    const reply =
      response.text;

    if (!reply || !reply.trim()) {

      return res.status(500).json({
        error:
          "Gemini хариу буцаасангүй."
      });

    }

    return res.status(200).json({
      reply: reply.trim()
    });

  }

  catch (error) {

    console.error(
      "Gemini Error:",
      error
    );

    return res.status(500).json({
      error:
        error?.message ||
        "Gemini API алдаа гарлаа."
    });

  }

}
