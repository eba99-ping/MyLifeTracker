import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('index.html','utf8');
const node=()=>({hidden:false,disabled:false,handlers:{},addEventListener(type,fn){this.handlers[type]=fn},querySelector(){return {append(){}}},focus(){this.focused=true}});
const start=node(),rocket=node();const stages=new Set(),timers=[];
const context=vm.createContext({Promise,setTimeout(fn,ms){timers.push({fn,ms})},window:{matchMedia(){return {matches:false}}},document:{getElementById(id){return id==='launchStart'?start:id==='launchRocketButton'?rocket:{classList:{add(value){stages.add(value)}}}},querySelectorAll(){return []}}});
const a=html.indexOf('    const introFinished='),b=html.indexOf('    const KEY',a);
vm.runInContext(html.slice(a,b),context);
assert.equal(stages.size,0);assert.equal(timers.length,0);
start.handlers.click();assert.equal(start.hidden,true);assert.equal(rocket.focused,true);assert(stages.has('is-started'));assert(!stages.has('is-playing'));assert.equal(timers.length,0);
rocket.handlers.click();assert.equal(rocket.disabled,true);assert(stages.has('is-playing'));assert.equal(timers.length,1);assert.equal(timers[0].ms,4200);
assert(!html.includes('Пуужинг товшоод хөөргөөрэй'));
console.log('PASS: start → cruising rocket → tap to boost → logo; no visible tap instruction or automatic boost');
